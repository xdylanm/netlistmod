def _netlist(body: str) -> Netlist:
    return Netlist.from_text(f"title\n{body}R9 a 0 1k\n.end\n", dialect=_XYCE)


def _text(body: str) -> bytes:
    return f"title\n{body}R9 a 0 1k\n.end\n".encode()


