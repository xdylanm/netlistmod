@pytest.mark.parametrize(
    ("name", "before", "edit", "message"), REFUSED, ids=[case[0] for case in REFUSED]
)
def test_refused(name: str, before: str, edit: Op, message: str) -> None:
    with pytest.raises(EditError, match=None) as captured:
        edit(_netlist(before))
    assert message in str(captured.value)


def test_the_other_dialects_keep_their_stimulus_edits() -> None:
    # Decision 0024: the per-dialect tables change nothing on ngspice and LTspice.
    lt = Netlist.from_text("t\nI1 a 0 PULSE(0 1 1n)\nR1 a 0 1\n.end\n", dialect=Dialect.LTSPICE)
    with pytest.raises(EditError, match="an LTspice I line needs one"):
        lt.remove_stimulus("I1")
    ng = Netlist.from_text("t\nV1 a 0 PWL(0 0 1n 1)\nR1 a 0 1\n.end\n", dialect=Dialect.NGSPICE)
    assert ng.set_stimulus_arg("V1", "r", "0").to_bytes() == (
        b"t\nV1 a 0 PWL(0 0 1n 1) r=0\nR1 a 0 1\n.end\n"
    )
    assert ng.remove_stimulus("V1").to_bytes() == b"t\nV1 a 0\nR1 a 0 1\n.end\n"
