@pytest.mark.parametrize(
    ("before", "edit", "message"),
    [case[1:] for case in REFUSED],
    ids=[case[0] for case in REFUSED],
)
def test_refused(before: str, edit: Op, message: str) -> None:
    with pytest.raises(EditError) as raised:
        edit(_netlist(before))
    assert message in str(raised.value)


def test_set_model_under_binning_off_finds_no_set() -> None:
    netlist = _netlist(".options parser model_binning=false\nM1 d g 0 0 nm\n")
    with pytest.raises(EditError, match="model `nch` is not defined"):
        netlist.set_model("M1", "nch")


@pytest.mark.parametrize("dialect", [Dialect.NGSPICE, Dialect.LTSPICE])
def test_ngspice_and_ltspice_area_edits_are_unchanged(dialect: Dialect) -> None:
    # A J's area stays positional on both; an M's `area` is left to the reparse, as before:
    # ngspice's M lists it, LTspice's does not.
    text = "t\nJ1 d g 0 jm temp=30\nM1 d g 0 0 nm\n.model jm njf\n.model nm nmos\n.end\n"
    netlist = Netlist.from_text(text, dialect=dialect)
    assert "J1 d g 0 jm 2 temp=30\n" in netlist.set_param("J1", "area", "2").text
    if dialect is Dialect.NGSPICE:
        assert "M1 d g 0 0 nm area=2\n" in netlist.set_param("M1", "area", "2").text
        return
    with pytest.raises(EditError) as raised:
        netlist.set_param("M1", "area", "2")
    assert "does not parse" in str(raised.value)
