"""The edit layer on xyce transistors (X-M4 B4; decision 0031 item 9; xm4-tasks 5.1 points 21 to 24
and G1 points 21 and 24): golden diffs with byte-exact expected text, and refusals.

``set_param(…, "area", …)`` on Q, J and Z replaces an area where it is written (positional or
``area=``) and otherwise adds ``area=v`` at the end of the line; an M has no area. ``set_model``
takes the name of a set of bins on M; ``set_model_param`` refuses one. ``area=``, ``IC=`` and
``TNODEOUT=`` are ordinary parameters. The expected texts are written by hand as replacements on
the input, not generated by the library.
"""

from __future__ import annotations

from collections.abc import Callable

import pytest

from netlistmod import Dialect, EditError, Netlist
from netlistmod.dialects import _XYCE

_MODELS = (
    ".model qm npn\n.model jm njf\n.model zm nmf\n.model nm nmos\n.model pm pmos\n"
    ".model nch.1 nmos lmin=1u lmax=2u\n.model nch.2 nmos lmin=2u lmax=4u\n"
    ".model mix.1 nmos\n.model mix.2 npn\n"
)


def _netlist(body: str, dialect: Dialect = _XYCE) -> Netlist:
    return Netlist.from_text(f"title\n{body}{_MODELS}.end\n", dialect=dialect)


def _text(body: str) -> bytes:
    return f"title\n{body}{_MODELS}.end\n".encode()


Op = Callable[[Netlist], Netlist]

