# Invariant: every allowed R, C or L edit keeps the topology and the text outside the line, and
# the edited line reads back with the value or model it was given (T5 tier).
_LINES = st.sampled_from(
    [
        "R1 a b 1k",
        "R1 a b R=1k",
        "R1 a b rmod 1k",
        "R1 a b rmod R=1k L=1u W=1u",
        "R1 a b rmod L=1u W=1u",
        "C1 a b 1p",
        "C1 a b C=1p",
        "C1 a b cmod 1p L=1u",
        "C1 a b cmod L=1u W=1u",
        "L1 a b 1u",
        "L1 a b L=1u",
    ]
)
_VALUES = st.sampled_from(["2", "4.7e3", "{rx*2}", "'rx+1'", "3MEG"])


@settings(max_examples=60, deadline=None)
@given(
    line=_LINES,
    value=_VALUES,
    operation=st.sampled_from(["set_value", "set_model", "remove_value"]),
)
def test_allowed_edits_keep_everything_else(line: str, value: str, operation: str) -> None:
    body = f".param rx=1k\n{line} ; note\n+ TEMP=27\nR9 b 0 1k\n"
    netlist = _netlist(body)
    designator = line.split()[0]
    element = netlist.element(designator)
    assert isinstance(element, Resistor | Capacitor | Inductor)
    model = {"R": "rres", "C": "cmod", "L": None}[designator[0]]
    try:
        if operation == "set_value":
            edited = netlist.set_value(designator, value)
        elif operation == "set_model":
            if model is None:
                return
            edited = netlist.set_model(designator, model)
        else:
            edited = netlist.remove_value(designator)
    except EditError:
        # Only the refusals that the rules name: an L, or a line left without its form.
        assert operation == "remove_value"
        return
    assert edited.signature() == netlist.signature()
    after = edited.element(designator)
    assert isinstance(after, Resistor | Capacitor | Inductor)
    if operation == "set_value":
        assert after.value is not None
        assert edited.slice(after.value.span) == value
        assert after.model == element.model or (
            after.model is not None
            and element.model is not None
            and after.model.model_name == element.model.model_name
        )
    elif operation == "set_model":
        assert after.model is not None and after.model.model_name == model
        if element.value is None:
            assert after.value is None
        else:
            assert after.value is not None
            assert edited.slice(after.value.span) == netlist.slice(element.value.span)
    else:
        assert after.value is None and after.model is not None
    # Only the edited line changed.
    start = netlist.element(designator).span.start
    assert edited.text[:start] == netlist.text[:start]
    assert edited.text.endswith(netlist.text[netlist.element("R9").span.start :])
