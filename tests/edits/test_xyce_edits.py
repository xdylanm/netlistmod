# The cases whose change is outside the body: the model or the `.include` line.
_OUTSIDE = {
    "model-param": _text("R1 a 0 rmod 1k\n").replace(b"RSH=100", b"RSH=50"),
    "include": _text("R1 a 0 1k\n").replace(b".end\n", b'.include "models.lib"\n.end\n'),
}


@pytest.mark.parametrize(
    ("name", "before", "edit", "after"), GOLDEN, ids=[case[0] for case in GOLDEN]
)
def test_golden(name: str, before: str, edit: Op, after: str) -> None:
    original = _netlist(before)
    edited = edit(original)
    expected = _OUTSIDE.get(name, _text(after))
    assert edited.to_bytes() == expected
    assert edited.signature() == original.signature()
    # The edited text loads again, as written.
    assert Netlist.from_text(expected.decode(), dialect=_XYCE).to_bytes() == expected


