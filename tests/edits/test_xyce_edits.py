"""The edit layer on xyce netlists (X-M1 B6; decision 0027 items 1, 3 and 5; xm1-tasks 5.1
points 9 to 11): golden diffs with byte-exact expected text, refusals and invariants.

R, C and L write the model right after the nodes, then the value (positional or ``R=``, ``C=``,
``L=``), so ``set_value`` inserts after the model and ``set_model`` right after the nodes;
``remove_value`` takes the whole field. The expected texts below are written by hand as
replacements on the input, not generated by the library.
"""

