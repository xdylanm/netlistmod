_LIB = ".model kc CORE\n.model dm2 D\n"


def _netlist(body: str) -> Netlist:
    return Netlist.from_text(f"title\n{body}{_MODELS}.end\n", dialect=_XYCE)


def _text(body: str) -> bytes:
    return f"title\n{body}{_MODELS}.end\n".encode()


Op = Callable[[Netlist], Netlist]

